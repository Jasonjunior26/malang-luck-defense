// data.js + game.js 를 서버(Deno Edge Function)에서 헤드리스로 돌릴 수 있는 단일 ES 모듈로 묶는다.
// 사용: node tools/build_engine.js   -> supabase/functions/submit-score/engine.js
// game.js / data.js 는 수정하지 않고 그대로 포함한다. DOM/canvas/오디오 의존은 래퍼의 스텁으로 대체.
// eval/new Function/node:vm 을 쓰지 않는다(Supabase Edge Runtime 은 동적 코드 생성이 막혀 있을 수 있음).
// 게임 규칙(data.js/game.js)이나 GAME_VER(ui.js)를 바꾸면 반드시 이 스크립트를 다시 실행하고 함수를 재배포할 것.
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const rd = (f) => fs.readFileSync(path.join(root, f), "utf8");
const data = rd("data.js"), game = rd("game.js"), ui = rd("ui.js");
const ver = (ui.match(/const GAME_VER = "([^"]+)"/) || [])[1];
if (!ver) throw new Error("ui.js 에서 GAME_VER 를 찾지 못함");
const sb = data.indexOf("// SEASONS-BEGIN"), se = data.indexOf("// SEASONS-END");
if (sb < 0 || se < sb) throw new Error("data.js 에서 SEASONS-BEGIN/END 를 찾지 못함");
const seasonSrc = data.slice(sb, se);
const strip = (s) => s.replace(/^\s*"use strict";\s*/, "");
const out = `// AUTO-GENERATED by tools/build_engine.js - 직접 수정 금지. (data.js + game.js, GAME_VER=${ver})
export const ENGINE_VER = ${JSON.stringify(ver)};

// ----- 시즌/닉네임 규칙: data.js 의 SEASONS-BEGIN~END 구간 (단일 출처) -----
${seasonSrc}
export { SEASONS, kstDate, dayDiff, seasonPhase, checkName };

// 시뮬 한 판을 헤드리스로 만든다. 반환 객체로 GAME.* / update 를 구동한다.
export function createEngine() {
  var window = undefined; // game.js 의 HEADLESS(typeof window === "undefined") 판정용
  const T = { over: null, sfx: 0 };
  const noop = () => {};
  const grad = () => ({ addColorStop: noop });
  const ctx0 = new Proxy({}, { get: (t, k) => (k in t ? t[k] : (k === "createLinearGradient" || k === "createRadialGradient") ? grad : k === "measureText" ? () => ({ width: 10 }) : noop), set: (t, k, v) => ((t[k] = v), true) });
  const elStub = { style: {}, dataset: {}, classList: { add: noop, remove: noop, toggle: noop, contains: () => false }, getContext: () => ctx0, addEventListener: noop, getBoundingClientRect: () => ({ width: 360, height: 400, left: 0, top: 0 }), width: 360, height: 400 };
  const $ = () => elStub;
  const performance = { now: () => 0 };
  const requestAnimationFrame = noop;
  // ui.js / graphics.js 쪽 함수 스텁 (시뮬 결과에 영향 없음)
  function sfx() { T.sfx++; } function vib() {} function updateHud() {} function uiLog() {} function uiBanner() {}
  function uiTicket() {} function uiUpTicket() {}
  function uiGameOver(r) { T.over = r; }
  function drawBoard() {} function drawUnit() {} function drawHero() {} function drawMob() {} function drawProj() {}
  function drawEfx() {} function drawPart() {} function drawParade() {} function gradeParticles() {}
  function drawMobBar() {}

// ===== data.js =====
${strip(data)}

// ===== game.js =====
${strip(game)}

// ===== 래퍼 =====
  let __seed = 0;
  dailySeed = function () { return __seed; }; // 서버는 클라이언트가 보낸(검증된) seed 로 판을 시작한다
  return {
    T, CONST, GAME, HEADLESS,
    get S() { return S; },
    update,
    start(seed) { __seed = seed >>> 0; T.over = null; GAME.start("daily"); return S; },
    result() { return T.over; },
  };
}
`;
const dst = path.join(root, "supabase", "functions", "submit-score", "engine.js");
fs.mkdirSync(path.dirname(dst), { recursive: true });
fs.writeFileSync(dst, out);
console.log("wrote", dst, out.length, "bytes, ver", ver);
